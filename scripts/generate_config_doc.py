#!/usr/bin/env python3
"""Generate docs/config.md from the typed configuration models so the reference cannot drift from the code."""

from __future__ import annotations

import argparse
import json
import re
import sys
import types
import typing
from pathlib import Path
from typing import Any

from pydantic import BaseModel
from pydantic.fields import FieldInfo
from pydantic_core import PydanticUndefined

from alien.config import schema
from alien.config.sources import SOURCE_TYPES

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "docs" / "config.md"

SOURCE_MODELS: list[type[BaseModel]] = [
    schema.MsigdbRemoteSource,
    schema.MsigdbRelease,
    schema.EnrichrRemoteSource,
    schema.EnrichrLibrary,
    schema.SymbolGmtSource,
    schema.MsigdbTsvSource,
    schema.CanonicalTsvSource,
    schema.MsigdbCacheSource,
    schema.PluginSource,
]
TARGET_MODELS: list[tuple[str, type[BaseModel]]] = [
    ("targets[]", schema.TargetSpec),
    ("targets[].annotation", schema.AnnotationSpec),
    ("targets[].annotation.metadata_fallbacks[]", schema.MetadataFallbackSpec),
    ("targets[].annotation.attributes", schema.GtfAttributes),
    ("targets[].output_genes / gene_filter", schema.GeneIdSpec),
]


SCALAR_NAMES: dict[Any, str] = {
    str: "string",
    bool: "boolean",
    int: "integer",
    float: "number",
    Any: "any",
    Path: "path",
}
MAX_INLINE_DEFAULT = 60


def _join(names: list[str]) -> str:
    return " \\| ".join(names)


def type_name(annotation: Any) -> str:
    origin = typing.get_origin(annotation)
    args = typing.get_args(annotation)
    if origin is typing.Annotated:
        text = type_name(args[0])
    elif origin is typing.Literal:
        text = _join([f"`{arg}`" for arg in args])
    elif origin in (typing.Union, types.UnionType):
        names = [type_name(arg) for arg in args if arg is not type(None)]
        text = _join(names + (["null"] if type(None) in args else []))
    elif origin in (list, dict):
        inner = ", ".join(type_name(arg) for arg in args)
        text = f"{'list' if origin is list else 'map'}[{inner}]"
    elif isinstance(annotation, type) and issubclass(annotation, BaseModel):
        text = "mapping"
    else:
        text = SCALAR_NAMES.get(annotation, getattr(annotation, "__name__", str(annotation)))
    return text


def default_text(field: FieldInfo) -> str:
    if field.is_required():
        return "required"
    value = field.default_factory() if field.default_factory is not None else field.default  # type: ignore[call-arg]
    if value is PydanticUndefined:
        return ""
    if isinstance(value, BaseModel):
        return "see below"
    if isinstance(value, Path):
        value = value.as_posix()
    text = json.dumps(value, default=str)
    return f"`{text}`" if len(text) <= MAX_INLINE_DEFAULT else "see `alien config show`"


def describe(field: FieldInfo) -> str:
    return re.sub(r"\s+", " ", field.description or "").strip().replace("|", "\\|")


def table(model: type[BaseModel], *, skip: tuple[str, ...] = ()) -> list[str]:
    lines = ["| Option | Type | Default | Description |", "|---|---|---|---|"]
    fields = sorted(model.model_fields.items(), key=lambda item: item[0] != "type")
    for name, field in fields:
        if name in skip:
            continue
        lines.append(f"| `{name}` | {type_name(field.annotation)} | {default_text(field)} | {describe(field)} |")
    return [*lines, ""]


def render() -> str:
    top = schema.AlienConfig.model_fields
    lines = [
        "# Configuration reference",
        "",
        "<!-- Generated by scripts/generate_config_doc.py from src/alien/config; do not edit by hand. -->",
        "",
        "Every key is validated: unknown keys and out-of-range values fail with the YAML path of the offending "
        "entry. Relative paths are resolved against the file that declares them. `alien config show [PRESET|FILE]` "
        "prints the effective configuration and `alien config schema` the JSON Schema "
        "([config.schema.json](config.schema.json)). [usage.md](usage.md) explains the options with examples.",
        "",
        "Top-level keys:",
        "",
        "| Key | Description |",
        "|---|---|",
        "| `extends` | A bundled preset name or another YAML file to start from; mappings merge, lists replace. |",
        *[f"| `{name}` | {describe(field)} |" for name, field in top.items()],
        "",
        "Four keys append to a list instead of replacing it: `gene_mapping.extra_non_gene_tokens`, "
        "`gene_mapping.extra_non_gene_token_regex`, `filtering.extra_broad_disease_regex` and "
        "`source_priority.extra.<family>`.",
        "",
    ]
    for name, field in top.items():
        annotation = field.annotation
        if isinstance(annotation, type) and issubclass(annotation, BaseModel):
            lines += [f"## `{name}`", "", *table(annotation)]
    lines += [
        "## `source_priority`",
        "",
        "A mapping from family to the ordered list of source tags. Defaults:",
        "",
        "```yaml",
        *(f"{family}: [{', '.join(tags)}]" for family, tags in schema.DEFAULT_SOURCE_PRIORITY.items()),
        "```",
        "",
        "## `filtering.exclude_terms`",
        "",
        "Bundled exclusion rules. Each removes matching terms of the listed source tags before size filtering; "
        "the removal is recorded as `excluded_term` with the rule name in `metadata/removed_terms_size_filter`. "
        "Turn one off with `filtering: {exclude_terms: {<rule>: {enabled: false}}}`.",
        "",
        "| Rule | Source tags | What it removes |",
        "|---|---|---|",
        *(
            f"| `{name}` | {', '.join(f'`{tag}`' for tag in rule['source_tags']) or 'all'} | "
            f"{rule['description'].replace('|', '\\|')} |"
            for name, rule in schema.DEFAULT_EXCLUDE_TERMS.items()
        ),
        "",
        "## `sources`",
        "",
        f"Each entry is selected by `type`: {', '.join(f'`{t}`' for t in SOURCE_TYPES)}. "
        "Every source also accepts `enabled` (default `true`).",
        "",
    ]
    for model in SOURCE_MODELS:
        type_field = model.model_fields.get("type")
        title = describe(type_field).rstrip(".") if type_field else f"`{model.__name__}`"
        if model is schema.MsigdbRelease:
            title = "`msigdb_remote` `release`"
        if model is schema.EnrichrLibrary:
            title = "`enrichr_remote` `libraries[]`"
        lines += [f"### {title}", "", *table(model, skip=("enabled",))]
    lines += ["## `targets`", "", f"Default: `{json.dumps(schema.DEFAULT_TARGETS)}`.", ""]
    for title, model in TARGET_MODELS:
        lines += [f"### `{title}`", "", *table(model)]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if docs/config.md is not up to date.")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            print("docs/config.md is out of date. Run scripts/generate_config_doc.py.", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
